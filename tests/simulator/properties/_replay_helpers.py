"""Builders for the replay-profile property tests (test-only, pure, offline).

The four ``replay``-profile property tests (P12, P13, P15, P17) drive the
:class:`~simulator.engine.ReplayEngine` end to end through a :class:`FakeSink`
and a :class:`TruthStore` in a temp directory (ADR-4, R20.7). They need two kinds
of input:

- **Small scenarios** (<=20 DTs, <=2 simulated hours) generated by Hypothesis so
  50 examples stay fast (ADR-4). :func:`small_flood_scenario` builds a structurally
  valid Scenario whose damage script may include a *flood-cause* trip on a DT that
  is placed **inside** an active Flood_Polygon, and :func:`small_grid_view` builds
  a matching :class:`GridView` where that DT's point lies in the flood polygon so
  the flood-cause geometry rule (R10.4) actually holds.
- **The full ``michaung-style`` scenario** for the single ``@example`` each test
  carries (R20.7). :func:`build_michaung_grid_view` reconstructs a real
  :class:`GridView` for that scenario by mirroring ``simulator.grid.build``'s
  assembly (topology + geometry via the geometry module), then guarantees the
  scenario's two flood-cause devices (``sub_004`` and ``dt_009``, per the shipped
  ``michaung-style`` damage script and task 5.4 "a substation inside the flood
  polygon") are sited inside the active Flood_Polygon so the flood-cause safety
  properties are meaningful on the real geometry.

Not product code: these live under ``tests/`` only and import nothing from
``boto3``/``botocore``. They read no wall clock, PID or network — the parent
``tests/conftest.py`` blocks sockets and freezes time.
"""

